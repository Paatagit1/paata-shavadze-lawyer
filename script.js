/* ენის შეცვლა */

function updateLanguage(
    language
) {
    const translation =
        translations[language];

    if (
        !translation
    ) {
        return;
    }

    currentLanguage =
        language;

    document.documentElement.lang =
        language;

    document.title =
        translation.pageTitle;

    translatedElements.forEach(
        (element) => {
            const key =
                element.dataset.i18n;

            if (
                translation[key]
            ) {
                element.textContent =
                    translation[key];
            }
        }
    );

    placeholderElements.forEach(
        (element) => {
            const key =
                element.dataset.i18nPlaceholder;

            if (
                translation[key]
            ) {
                element.placeholder =
                    translation[key];
            }
        }
    );

    languageButtons.forEach(
        (button) => {
            const selected =
                button.dataset.language ===
                language;

            button.classList.toggle(
                "active",
                selected
            );

            button.setAttribute(
                "aria-pressed",
                String(
                    selected
                )
            );
        }
    );

    renderServices(
        language
    );

    renderServiceOptions(
        language
    );

    renderNews(
        language
    );

    formNotice.classList.remove(
        "success"
    );

    formNotice.textContent =
        translation.formPrivacy;

    try {
        localStorage.setItem(
            "paata-shavadze-language",
            language
        );
    } catch {
        // შენახვის გარეშე საიტი ჩვეულებრივ მუშაობს.
    }
}

languageButtons.forEach(
    (button) => {
        button.addEventListener(
            "click",
            () => {
                updateLanguage(
                    button.dataset.language
                );
            }
        );
    }
);

