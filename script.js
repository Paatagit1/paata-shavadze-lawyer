consultationForm.addEventListener(
    "submit",
    async (event) => {
        event.preventDefault();

        const translation =
            translations[currentLanguage];

        const formData =
            new FormData(
                consultationForm
            );

        const message = [
            `${translation.formName}: ${formData.get("name")}`,

            `${translation.formEmail}: ${formData.get("email")}`,

            `${translation.formService}: ${formData.get("service")}`,

            "",

            `${translation.formMessage}:`,

            formData.get(
                "message"
            )
        ].join(
            "\n"
        );

        window.open(
            FACEBOOK_URL,
            "_blank",
            "noopener,noreferrer"
        );

        try {
            if (
                !navigator.clipboard ||
                !navigator.clipboard.writeText
            ) {
                throw new Error(
                    "Clipboard unavailable"
                );
            }

            await navigator.clipboard.writeText(
                message
            );

            formNotice.textContent =
                translation.formCopied;
        } catch {
            formNotice.textContent =
                translation.formOpened;
        }

        formNotice.classList.add(
            "success"
        );
    }
);

