searchForm.addEventListener(
    "submit",
    (event) => {
        event.preventDefault();

        const query =
            searchInput.value
                .trim()
                .toLowerCase();

        if (
            !query
        ) {
            return;
        }

        const searchTargets =
            document.querySelectorAll(
                "h1, h2, h3, p"
            );

        const match =
            Array.from(
                searchTargets
            ).find(
                (element) => {
                    return element.textContent
                        .toLowerCase()
                        .includes(
                            query
                        );
                }
            );

        if (
            match
        ) {
            match.scrollIntoView(
                {
                    behavior:
                        "smooth",

                    block:
                        "center"
                }
            );

            match.style.transition =
                "background-color 0.3s ease";

            match.style.backgroundColor =
                "#fff1cb";

            window.setTimeout(
                () => {
                    match.style.backgroundColor =
                        "";
                },
                1800
            );
        }
    }
);

