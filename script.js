function showSlide(
    index
) {
    currentSlide =
        (
            index +
            slides.length
        ) %
        slides.length;

    slides.forEach(
        (slide, slideIndex) => {
            slide.classList.toggle(
                "active",
                slideIndex ===
                currentSlide
            );
        }
    );

    sliderDots.forEach(
        (dot, dotIndex) => {
            dot.classList.toggle(
                "active",
                dotIndex ===
                currentSlide
            );
        }
    );
}

function startSlider() {
    window.clearInterval(
        sliderTimer
    );

    sliderTimer =
        window.setInterval(
            () => {
                showSlide(
                    currentSlide + 1
                );
            },
            6500
        );
}

