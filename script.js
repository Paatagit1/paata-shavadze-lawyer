function renderServices(
    language
) {
    const services =
        translations[language].services;

    servicesGrid.innerHTML =
        "";

    services.forEach(
        (service, index) => {
            const card =
                document.createElement(
                    "a"
                );

            card.href =
                "#consultation";

            card.className =
                "service-card";

            card.innerHTML = `
                <span class="service-number">
                    ${String(index + 1).padStart(2, "0")}
                </span>

                <h3>
                    ${service.title}
                </h3>

                <p>
                    ${service.description}
                </p>
            `;

            servicesGrid.appendChild(
                card
            );
        }
    );
}

